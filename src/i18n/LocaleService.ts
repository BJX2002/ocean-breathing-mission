function toSimplifiedPrototype(value: string): string {
  return [...value].map((character) => SIMPLIFIED_CHARACTER_MAP[character] ?? character).join('');
}

/**
 * Minimal bilingual string service. Keeps user-facing text out of scenes so the
 * MVP can ship an English + Traditional Chinese UI. Falls back to the key when a
 * translation is missing.
 */
class LocaleService {
  private current: LocaleCode = 'zh-Hant';

  setLocale(code: LocaleCode): void {
    this.current = code;
  }

  getLocale(): LocaleCode {
    return this.current;
  }

  /** Translate a key for the current locale. */
  t(key: string): string {
    const value = tables[this.current][key] ?? key;
    return this.current === 'zh-Hans' ? toSimplifiedPrototype(value) : value;
  }
}

export const i18n = new LocaleService();
